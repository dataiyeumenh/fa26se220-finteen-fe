param(
    [Parameter(Mandatory=$true)][string]$Source,
    [Parameter(Mandatory=$true)][string]$Target
)

$word = New-Object -ComObject Word.Application
$word.Visible = $false
$word.DisplayAlerts = 0

function Replace-Exact([object]$doc, [string]$old, [string]$new) {
    $range = $doc.Content
    $find = $range.Find
    $find.ClearFormatting()
    $find.Text = $old
    $find.Forward = $true
    $find.Wrap = 0
    if (-not $find.Execute()) { throw "Text not found: $old" }
    $range.Text = $new
}

try {
    $doc = $word.Documents.Open($Source, $false, $false)

    Replace-Exact $doc `
        'Figure 3. Current system context. PayOS is integrated in production. The language-model summary remains a stretch item and is not implemented.' `
        'Figure 3. Current system context. PayOS runs in production. Firebase provides Google sign-in, Brevo provides SMTP mail, Cloudflare provides CDN delivery, and Gemini with OpenRouter fallback supports Studio reading suggestions. GitHub Actions with VieNeu-TTS pre-generates narration audio. The Android application remains planned for a later iteration.'

    Replace-Exact $doc `
        'Figure 4. PARENT and TEACHER plan capabilities. PayOS purchases grant time-limited entitlements; current production prices are administrator-set test values.' `
        'Figure 4. PARENT and TEACHER plan capabilities. Both plans include the chapter game and learner reports. PayOS purchases grant time-limited entitlements; current production prices are administrator-set test values, and one open group is allowed per owner and context.'

    $fe14 = $doc.Content
    $fe14.Find.Text = 'FE-14:'
    $fe14.Find.Forward = $true
    $fe14.Find.Wrap = 0
    if (-not $fe14.Find.Execute()) { throw 'FE-14 not found' }
    $paragraph = $fe14.Paragraphs.Item(1).Range
    $paragraph.Text = 'FE-14: Voice narration is generated ahead of play with VieNeu-TTS. Dialogue text is hashed so only changed lines are regenerated by GitHub Actions; the audio files are stored on the VPS and no generation occurs while a learner is playing. Narration is currently available for CH01-CH03; CH04-CH08 do not yet have narration audio.' + "`r"

    $doc.Tables.Item(1).Cell(8,4).Range.Text = 'Aligned Report 1 wording with the current SRS, BM04 and production; corrected the system-context description, TEACHER capabilities and CH01-CH03 narration coverage. Existing diagrams were retained unchanged.'

    $doc.SaveAs2($Target, 16)
    $doc.Close($false)
}
finally {
    $word.Quit()
}
