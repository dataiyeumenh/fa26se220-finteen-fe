param(
    [Parameter(Mandatory=$true)][string]$Source,
    [Parameter(Mandatory=$true)][string]$Target,
    [Parameter(Mandatory=$true)][string]$Assets
)

$word = New-Object -ComObject Word.Application
$word.Visible = $false
$word.DisplayAlerts = 0

function Replace-Exact([object]$doc, [string]$old, [string]$new) {
    $range = $doc.Content
    $find = $range.Find
    $find.ClearFormatting()
    $find.Text = $old
    $find.Forward = $true
    $find.Wrap = 0
    if (-not $find.Execute()) { throw "Text not found: $old" }
    $range.Text = $new
}

try {
    $doc = $word.Documents.Open($Source, $false, $false)

    Replace-Exact $doc `
        'Figure 3. Current system context. PayOS is integrated in production. The language-model summary remains a stretch item and is not implemented.' `
        'Figure 3. Current system context. FinTeen integrates with PayOS for production payments, Firebase for Google sign-in, Brevo for SMTP mail, Cloudflare for CDN delivery, Gemini with OpenRouter fallback for Studio reading suggestions, and GitHub Actions with VieNeu-TTS for pre-generated narration audio. The Android application remains planned for a later iteration and is not shown as a delivered client.'

    Replace-Exact $doc `
        'Figure 4. PARENT and TEACHER plan capabilities. PayOS purchases grant time-limited entitlements; current production prices are administrator-set test values.' `
        'Figure 4. PARENT and TEACHER plan capabilities. Both plans include the chapter game and learner reports. PayOS purchases grant time-limited entitlements; current production prices are administrator-set test values, and one open group is allowed per owner and context.'

    $fe14 = $doc.Content
    $fe14.Find.Text = 'FE-14:'
    $fe14.Find.Forward = $true
    $fe14.Find.Wrap = 0
    if (-not $fe14.Find.Execute()) { throw 'FE-14 not found' }
    $para = $fe14.Paragraphs.Item(1).Range
    $para.Text = 'FE-14: Voice narration is generated ahead of play with VieNeu-TTS. Dialogue text is hashed so only changed lines are regenerated by GitHub Actions; the audio files are stored on the VPS and no generation occurs while a learner is playing. Narration is currently available for CH01-CH03; CH04-CH08 do not yet have narration audio.' + "`r"

    $doc.Tables.Item(1).Cell(8,4).Range.Text = 'Aligned Report 1 with the current SRS, BM04 and production; refreshed Figures 3 to 5 and added editable draw.io sources; corrected external services, TEACHER capabilities and CH01-CH03 narration coverage.'

    $replacements = @(
        @{ Index = 4; File = 'figure3-context.png' },
        @{ Index = 5; File = 'figure4-plans.png' },
        @{ Index = 6; File = 'figure5-records.png' }
    )
    foreach ($item in $replacements) {
        $shape = $doc.InlineShapes.Item($item.Index)
        $range = $shape.Range.Duplicate
        $width = $shape.Width
        $shape.Delete()
        $newShape = $doc.InlineShapes.AddPicture((Join-Path $Assets $item.File), $false, $true, $range)
        $newShape.LockAspectRatio = -1
        $newShape.Width = $width
    }

    $formatDocx = 16
    $doc.SaveAs2($Target, $formatDocx)
    $doc.Close($false)
}
finally {
    $word.Quit()
}
