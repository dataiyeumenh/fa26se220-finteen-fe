from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
import sys

from docx import Document


source = Path(sys.argv[1])
target = Path(sys.argv[2])
assets = Path(sys.argv[3])
temp = target.with_suffix(".tmp.docx")

doc = Document(source)


def replace_start(prefix, text):
    for paragraph in doc.paragraphs:
        if paragraph.text.strip().startswith(prefix):
            paragraph.text = text
            return
    raise ValueError(prefix)


replace_start(
    "Figure 3.",
    "Figure 3. Current system context. FinTeen integrates with PayOS for production payments, Firebase for Google sign-in, Brevo for SMTP mail, Cloudflare for CDN delivery, Gemini with OpenRouter fallback for Studio reading suggestions, and GitHub Actions with VieNeu-TTS for pre-generated narration audio. The Android application remains planned for a later iteration and is not shown as a delivered client.",
)
replace_start(
    "FE-14:",
    "FE-14: Voice narration is generated ahead of play with VieNeu-TTS. Dialogue text is hashed so only changed lines are regenerated by GitHub Actions; the audio files are stored on the VPS and no generation occurs while a learner is playing. Narration is currently available for CH01–CH03; CH04–CH08 do not yet have narration audio.",
)
replace_start(
    "Figure 4.",
    "Figure 4. PARENT and TEACHER plan capabilities. Both plans include the chapter game and learner reports. PayOS purchases grant time-limited entitlements; current production prices are administrator-set test values, and one open group is allowed per owner and context.",
)

record = doc.tables[0].rows[7]
record.cells[3].text = "Aligned Report 1 with the current SRS, BM04 and production; refreshed Figures 3 to 5 and added editable draw.io sources; corrected external services, TEACHER capabilities and CH01–CH03 narration coverage."

target.parent.mkdir(parents=True, exist_ok=True)
doc.save(temp)

with ZipFile(temp, "r") as zin, ZipFile(target, "w", ZIP_DEFLATED) as zout:
    for item in zin.infolist():
        if item.filename == "word/media/image4.png":
            data = (assets / "figure3-context.png").read_bytes()
        elif item.filename == "word/media/image2.png":
            data = (assets / "figure4-plans.png").read_bytes()
        elif item.filename == "word/media/image3.png":
            data = (assets / "figure5-records.png").read_bytes()
        else:
            data = zin.read(item.filename)
        zout.writestr(item, data)

temp.unlink()
print(target)
