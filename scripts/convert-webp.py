"""Convert local raster assets without changing dimensions or deleting originals.

Requires Pillow with WebP support: python scripts/convert-webp.py
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import json
from PIL import Image, features

ROOT = Path(__file__).resolve().parents[1]
EXTENSIONS = {".png", ".jpg", ".jpeg", ".bmp", ".tiff"}


def convert(source):
    target = source.with_suffix(".webp")
    if not target.exists() or target.stat().st_mtime < source.stat().st_mtime:
        with Image.open(source) as original:
            image = original.convert("RGBA" if "A" in original.getbands() or "transparency" in original.info else "RGB")
            image.save(target, "WEBP", quality=86, method=4,
                       lossless="brand" in source.parts or max(image.size) <= 512,
                       exact=True)
    with Image.open(source) as original, Image.open(target) as result:
        assert original.size == result.size, str(source)
        assert result.format == "WEBP", str(target)
        if "A" in original.getbands():
            assert original.getchannel("A").tobytes() == result.convert("RGBA").getchannel("A").tobytes(), str(source)
    return source, target, source.stat().st_size, target.stat().st_size


if __name__ == "__main__":
    assert features.check("webp"), "Pillow needs WebP support"
    sources = sorted(p for folder in [ROOT / "public", ROOT / "src/assets"]
                     for p in folder.rglob("*") if p.suffix.lower() in EXTENSIONS)
    rows = []
    with ThreadPoolExecutor(max_workers=2) as pool:
        for index, row in enumerate(pool.map(convert, sources), 1):
            rows.append(row)
            if index % 25 == 0:
                print(f"Converted {index}/{len(sources)} images", flush=True)
    mapping = {"/" + source.relative_to(ROOT / "public").as_posix():
               "/" + target.relative_to(ROOT / "public").as_posix()
               for source, target, _, _ in rows if source.is_relative_to(ROOT / "public")}
    (ROOT / "src/lib/webpAssets.js").write_text(
        "// Generated by scripts/convert-webp.py; originals stay available locally.\n"
        + "export const webpAssets = " + json.dumps(mapping, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    report = {"count": len(rows), "originalBytes": sum(row[2] for row in rows),
              "webpBytes": sum(row[3] for row in rows)}
    (ROOT / "output").mkdir(exist_ok=True)
    (ROOT / "output/webp-conversion.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report), flush=True)
