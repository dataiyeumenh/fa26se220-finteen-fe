import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE || 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
const base = process.env.STUDIO_TEST_BASE || 'http://localhost:5173'
try {
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 900 } })
    const page = await context.newPage()
    page.setDefaultTimeout(15000)
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.route('**/*', route => route.request().method() !== 'GET' ? route.abort() : route.continue())
    await page.goto(`${base}/tests/fixtures/studio-game-preview-browser.html`)
    const click = text => page.getByRole('button', { name: text, exact: true }).click()
    const scene = id => page.waitForFunction(id => document.querySelector('.vn-player')?.dataset.sceneId === id, id)
    const exit = () => page.locator('.vn-toolbar-left [aria-label="Quay lại trình soạn"]').click()
    await page.locator('textarea.stage-text').fill('Nháp chưa lưu vẫn chạy trong game thật')
    await click('Chơi thử từ đầu'); await scene('INTRO')
    assert.match(await page.locator('.vn-dialogue').innerText(), /Nháp chưa lưu/)
    const box = await page.locator('.studio-game-preview').boundingBox()
    assert.equal(box.x, 0); assert.equal(box.y, 0); assert.equal(box.width, width); assert.equal(box.height, 900)
    await page.locator('.vn-dialogue-next').click()
    await scene('CARD'); await page.locator('.vn-inspect-button').click()
    assert.match(await page.locator('.vn-inspect-paper').innerText(), /Thông tin trong bản nháp/)
    await page.locator('.vn-inspect-done').click(); await scene('CHOICE')
    assert.equal(await page.locator('.vn-choice-option').first().isDisabled(), false)
    await page.locator('.vn-choice-option').first().click(); await scene('END')
    assert.match(await page.locator('.vn-ending-panel').innerText(), /Kết chương trong game thật/)
    await exit()
    assert.equal(await page.locator('textarea.stage-text').inputValue(), 'Nháp chưa lưu vẫn chạy trong game thật')
    await click('Cá nhân hóa'); await click('Chơi thử từ đầu'); await scene('INTRO')
    assert.match(await page.locator('.vn-dialogue').innerText(), /Bản riêng cho trẻ thích thể thao/)
    await exit()
    await page.getByRole('button', { name: 'Cảnh 4: Chọn cách làm', exact: true }).click()
    await click('Chơi thử từ cảnh này'); await scene('CHOICE')
    assert.equal(await page.locator('.vn-choice-option').first().isDisabled(), true, 'A new run inherited an inspected card')
    await page.locator('.vn-choice-option').nth(1).click(); await scene('GAME')
    await page.locator('.nw-game').waitFor()
    await exit()
    await page.getByRole('button', { name: 'Cảnh 5: Phân loại', exact: true }).click()
    await click('Chơi thử từ cảnh này'); await scene('GAME')
    await page.locator('.vn-menu > summary').click(); await click('Sửa cảnh này')
    assert.equal(await page.locator('.scene-inspector-heading h2').innerText(), 'Cảnh 5')
    // Explicit learner props must still be ignored in preview mode.
    await page.evaluate(() => window.previewQA.mountDirect('END')); await scene('END')
    await page.locator('.vn-menu > summary').click()
    await page.getByRole('button', { name: /^Giọng đọc:/ }).click()
    await page.locator('.vn-restart-confirm > summary').click(); await click('Bắt đầu lại chương'); await scene('INTRO')
    await page.evaluate(() => window.previewQA.mountDirect('CHECK')); await scene('CARD')
    const result = await page.evaluate(() => ({ calls: window.previewQA.calls, storageUnchanged: window.previewQA.checkStorage(), saved: window.previewQA.saved }))
    assert.deepEqual(result.calls, [], 'Preview invoked a learner API or flushed a pending batch')
    assert.equal(result.storageUnchanged, true, 'Preview changed learner checkpoints, pending results or voice preference')
    assert.equal(result.saved, null, 'Preview saved the draft')
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ width, passed: true, checks: ['real fullscreen player', 'unsaved draft', 'inspect and automatic branch', 'choices and ending report', 'personalization', 'fresh state and locks', 'real minigame', 'return to edit', 'restart', 'no learner API/storage writes'] }))
    await context.close()
  }
} finally { await browser.close() }
